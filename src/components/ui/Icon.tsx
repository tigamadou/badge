// une fonction (composant icone) a travers la frontiere client. Ils rendent donc
// une icone par NOM serialisable, resolu ici. `Icon` est utilisable en Server ET
// Client Components (il *rend* une icone lucide, ce qui est autorise en RSC ; c'est
